"""TDEV power-law fit: parameter recovery on synthetic data with known truth.

The whole point of tdev.py is to replace literature constants with measured
ones, so the first thing to prove is that the estimator actually recovers
known (c, e) from data generated by the model it assumes — and that the
uncertainty it reports (bootstrap CIs, residual sigma) is honest.
"""

import numpy as np
import pytest

from metis_benchmark.tdev import (
    HOURS_PER_PERSON_MONTH,
    WEEKS_PER_MONTH,
    TdevFit,
    fit_tdev,
    predict_tdev_interval,
)


def _synthetic(c: float, e: float, sigma: float, n: int, seed: int):
    # PM spread over ~2.5 decades (0.5 .. 150 person-months), like Track A.
    rng = np.random.default_rng(seed)
    pm = np.exp(rng.uniform(np.log(0.5), np.log(150.0), size=n))
    # Multiplicative log-normal noise: exactly the model the fit assumes.
    tdev = c * pm**e * np.exp(rng.normal(0.0, sigma, size=n))
    return pm, tdev


def test_fit_recovers_known_coefficients():
    # Truth deliberately set at the literature values the experiment tests.
    pm, tdev = _synthetic(c=3.67, e=0.30, sigma=0.25, n=400, seed=0)
    fit = fit_tdev(pm, tdev, n_boot=500, seed=0)
    # With n=400 and sigma=0.25 the estimates concentrate tightly around truth.
    assert abs(fit.c - 3.67) < 0.25
    assert abs(fit.e - 0.30) < 0.03
    # The residual scale must match the injected noise level.
    assert abs(fit.sigma - 0.25) < 0.03
    # And the bootstrap CIs must contain the truth.
    assert fit.c_ci[0] < 3.67 < fit.c_ci[1]
    assert fit.e_ci[0] < 0.30 < fit.e_ci[1]
    assert fit.n == 400


def test_fit_is_exact_on_noiseless_data():
    # sigma=0 -> the log-log points are exactly collinear: the fit must return
    # the generating law to numerical precision, with zero residual and R^2=1.
    pm = np.array([1.0, 4.0, 10.0, 40.0, 100.0])
    tdev = 2.5 * pm**0.35
    fit = fit_tdev(pm, tdev, n_boot=50, seed=0)
    assert fit.c == pytest.approx(2.5, rel=1e-9)
    assert fit.e == pytest.approx(0.35, rel=1e-9)
    assert fit.sigma == pytest.approx(0.0, abs=1e-9)
    assert fit.r2 == pytest.approx(1.0, abs=1e-9)


def test_fit_rejects_bad_inputs():
    with pytest.raises(ValueError):
        fit_tdev(np.array([1.0, -2.0, 3.0]), np.array([1.0, 2.0, 3.0]))
    with pytest.raises(ValueError):
        fit_tdev(np.array([1.0, 2.0, 3.0]), np.array([1.0, 0.0, 3.0]))
    with pytest.raises(ValueError):
        fit_tdev(np.array([1.0, 2.0]), np.array([1.0, 2.0]))  # n < 3
    with pytest.raises(ValueError):
        fit_tdev(np.array([1.0, 2.0, 3.0]), np.array([1.0, 2.0]))  # shapes


def test_predict_interval_point_math_and_units():
    # sigma=0 -> the band collapses onto the point; the point must be the
    # power law in months converted to weeks.
    point, lo, hi = predict_tdev_interval(8.0, c=3.67, e=0.30, sigma=0.0)
    expected_weeks = 3.67 * 8.0**0.30 * WEEKS_PER_MONTH
    assert point == pytest.approx(expected_weeks)
    assert lo == pytest.approx(expected_weeks)
    assert hi == pytest.approx(expected_weeks)


def test_predict_interval_band_is_symmetric_in_log_space():
    point, lo, hi = predict_tdev_interval(
        np.array([2.0, 20.0, 200.0]), c=3.0, e=0.3, sigma=0.4, level=0.90
    )
    # Multiplicative band: upper/point == point/lower at every scale, and the
    # log half-width equals z90 * sigma (z90 ~ 1.6449).
    assert np.allclose(hi / point, point / lo)
    assert np.allclose(np.log(hi / point), 1.6448536269514722 * 0.4)
    # Lower bound stays positive by construction.
    assert np.all(lo > 0)


def test_predict_interval_band_covers_synthetic_truth():
    # End-to-end honesty: fit on synthetic data, predict on fresh draws from
    # the same law, and check the nominal-90% band covers ~90% of them.
    pm_fit, tdev_fit = _synthetic(c=3.0, e=0.32, sigma=0.3, n=500, seed=1)
    fit = fit_tdev(pm_fit, tdev_fit, n_boot=200, seed=1)
    pm_new, tdev_new = _synthetic(c=3.0, e=0.32, sigma=0.3, n=4000, seed=2)
    _, lo, hi = predict_tdev_interval(pm_new, fit.c, fit.e, fit.sigma, level=0.90)
    covered = np.mean((tdev_new * WEEKS_PER_MONTH >= lo) & (tdev_new * WEEKS_PER_MONTH <= hi))
    assert 0.87 <= covered <= 0.93


def test_predict_interval_rejects_bad_inputs():
    with pytest.raises(ValueError):
        predict_tdev_interval(-1.0, 3.67, 0.3, 0.1)
    with pytest.raises(ValueError):
        predict_tdev_interval(1.0, 3.67, 0.3, -0.1)
    with pytest.raises(ValueError):
        predict_tdev_interval(1.0, 3.67, 0.3, 0.1, level=1.0)


def test_constants_match_product_conventions():
    # The PM conversion must be the product's 152 h/PM; a silent change here
    # would shift every fitted coefficient.
    assert HOURS_PER_PERSON_MONTH == 152.0
    assert WEEKS_PER_MONTH == pytest.approx(52.0 / 12.0)
    assert isinstance(fit_tdev(np.array([1.0, 2, 4]), np.array([2.0, 3, 4])), TdevFit)

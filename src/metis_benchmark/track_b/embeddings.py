"""Local sentence embeddings for the Track B semantic channel.

Each task's text is projected to a dense vector with BAAI/bge-small-en-v1.5
(384-d, local, normalized). Embeddings are deterministic — the model is never
trained here — so they leak nothing about effort; they only encode meaning, so
that semantically similar tasks land close in cosine angle (V20 Fig 2).

Embedding 12k-23k texts is the slow step, so the matrix is cached to disk per
dataset (data/processed/emb_<key>_<digest>.npy) and reused. The cache is keyed
by CONTENT — md5 of the model name plus every input text, the same scheme as
track_b.multilingual — so any change to the model, the loader, or a single
text automatically invalidates it. (The previous key was model + row count
only, which could serve a stale matrix whenever texts changed but the count
did not; caches under that legacy 8-hex-digit tag are orphaned and are simply
regenerated by scripts/embed_track_b.py, ~1 min for all three datasets.)
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np

MODEL_NAME = "BAAI/bge-small-en-v1.5"
_CACHE_DIR = Path(__file__).resolve().parents[3] / "data" / "processed"

# Lazily instantiated singleton so the (heavy) model loads at most once.
_model = None


def _get_model():
    global _model
    if _model is None:
        # Imported lazily: sentence-transformers pulls torch, which we only want
        # to load when embeddings are actually needed.
        from sentence_transformers import SentenceTransformer

        _model = SentenceTransformer(MODEL_NAME)
    return _model


def _cache_path(key: str, texts: list[str]) -> Path:
    # Content key: model + every text, in order (the multilingual.py scheme,
    # 16 hex chars). Any change in the inputs yields a different file, so a
    # cache hit is by construction the matrix of exactly these texts.
    digest = hashlib.md5("\n".join([MODEL_NAME, *texts]).encode("utf-8")).hexdigest()[:16]
    return _CACHE_DIR / f"emb_{key}_{digest}.npy"


def embed_texts(texts: list[str], key: str) -> np.ndarray:
    """Return the (n, 384) normalized embedding matrix for `texts`, cached.

    `key` only makes the cache filename human-readable; correctness comes from
    the content digest (model + texts) in the name, which a changed loader or
    model invalidates automatically.
    """
    n = len(texts)
    cache = _cache_path(key, texts)
    if cache.exists():
        emb = np.load(cache)
        # The digest already guarantees the content; the shape check is a
        # last-resort guard against a truncated/corrupted file on disk.
        if emb.shape[0] == n:
            return emb
    model = _get_model()
    # normalize_embeddings=True -> unit vectors, so a dot product is the cosine
    # similarity used by the k-NN retrieval.
    emb = model.encode(
        texts, normalize_embeddings=True, batch_size=128, show_progress_bar=True
    ).astype(np.float32)
    _CACHE_DIR.mkdir(parents=True, exist_ok=True)
    np.save(cache, emb)
    return emb
